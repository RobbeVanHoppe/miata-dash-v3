"""The ESP32 C code in esp32/lib/miata_can is generated from can/miata.dbc.
Fail if someone edits the DBC without regenerating (see esp32/README.md)."""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "esp32" / "lib" / "miata_can" / "src"
STAMP = re.compile(r"generated by cantools version .*")


def normalise(text: str) -> str:
    return STAMP.sub("generated by cantools", text)


def test_generated_c_matches_dbc(tmp_path):
    subprocess.run(
        [sys.executable, "-m", "cantools", "generate_c_source", str(ROOT / "can" / "miata.dbc"),
         "--database-name", "miata", "-o", str(tmp_path)],
        check=True, capture_output=True, stdin=subprocess.DEVNULL,  # no inherited console handle on Windows
    )
    for name in ("miata.h", "miata.c"):
        fresh = normalise((tmp_path / name).read_text(encoding="utf-8"))
        committed = normalise((GENERATED / name).read_text(encoding="utf-8"))
        assert fresh == committed, f"{name} is stale: regenerate from can/miata.dbc"
